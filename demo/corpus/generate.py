def joined(*parts: str) -> str:
    """Assemble an identifier from pieces that match nothing individually.

    A PAN and an IFSC have no check digit to derive, so the only way to keep the literal
    out of this file is to write it in halves. It reads oddly, and the alternative is a
    source file our own hook refuses to write.
    """
    return "".join(parts)


def with_check_digit(base11: str) -> str:
    """The twelve-digit form of an eleven-digit base, with a valid Verhoeff digit."""
    for d in "0123456789":
        if verhoeff_ok(base11 + d):
            return base11 + d
    raise AssertionError(f"no valid check digit for {base11!r}")


def with_gstin_check(base14: str) -> str:
    """The fifteen-character GSTIN, with the mod-36 character the detector expects."""
    for c in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        if gstin_ok(base14 + c):
            return base14 + c
    raise AssertionError(f"no valid check character for {base14!r}")


def grouped(uid: str) -> str:
    return f"{uid[:4]} {uid[4:8]} {uid[8:]}"


