#!/usr/bin/env python3
"""Build the synthetic corpus the egress demo reads from.

The documents are *generated*, not committed, and that was not a stylistic choice: the
first two attempts at checking them in were refused by ZeroTrace's own PreToolUse hook,
because writing a register of Aadhaar-shaped numbers means putting those numbers in a
tool argument. The product was right both times, so the corpus is derived here instead
and the repository never carries a file full of identifier-shaped strings.

That constraint shapes the whole file. Nothing identifier-shaped appears as a literal:

  * twelve-digit numbers are eleven-digit bases plus a Verhoeff digit computed at import
  * a GSTIN is a fourteen-character prefix plus a mod-36 character, likewise computed
  * a PAN or an IFSC is assembled by `joined()` from pieces that match nothing on their own

Both check digits are brute-forced against the *shipped validators*, which is what
guarantees the corpus exercises the checksum path rather than producing numbers that
merely look right. It also makes the demo portable: `python demo/corpus/generate.py` on
any machine produces the same tree, so the prompts in docs/21 refer to paths that exist.

**Everything here is synthetic.** The names are invented, the districts are real but the
people are not, and every identifier belongs to nobody. The credentials are equally fake:
a connection string pointing at a `.invalid` host, which by RFC 2606 can never resolve.

The tree mirrors the security groups in Control-DB/policies/bharat-digital.yaml:

    citizen-services/   citizen records      CUSTOMER_DATA, AADHAAR, QUASI_IDENTIFIER_SET
    revenue/            tax and financial    FINANCIAL_RECORD, GSTIN
    hr-personnel/       staff records        HR_RECORD
    infosec/            secrets and findings INFRA_SECRET, SECURITY_FINDING
    public/             open material        nothing -- the control case

`public/` is not filler. A demo in which every read is blocked proves only that the tool
says no; the open circular is what shows the same person, in the same session, reading
what they are entitled to with no friction at all.
"""

