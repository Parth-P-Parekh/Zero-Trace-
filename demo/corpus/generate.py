SECTIONS = {
    "citizen-services": citizen_services,
    "revenue": revenue,
    "hr-personnel": hr_personnel,
    "infosec": infosec,
    "public": public,
}


def build() -> list[Path]:
    written: list[Path] = []
    for group, make in SECTIONS.items():
        folder = TREE / group
        folder.mkdir(parents=True, exist_ok=True)
        for name, text in make().items():
            path = folder / name
            path.write_text(text, encoding="utf-8")
            written.append(path)
    return written


def main() -> int:
    written = build()
    print(f"corpus written to {TREE}")
    for path in written:
        print(f"  {path.relative_to(TREE)}")
    print()
    print("Now run:  zerotrace login s.iyer   (or r.banerjee, m.khan, a.das, cag.audit)")
    print("then ask Claude Code to read one of these files. See docs/21_EGRESS_DEMO.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
